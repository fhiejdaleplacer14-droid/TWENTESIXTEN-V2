function sachets() {
  const colours = ['#c9382f', '#e8c14a', '#2f4f9a', '#3aa6a0', '#e07a3a'];
  const rects = [['#5c4630', 0, 0, 16, 1]];
  for (let col = 0; col < 4; col++) {
    for (let row = 0; row < 3; row++) rects.push([colours[(col + row * 2) % colours.length], 1 + col * 4, 1 + row * 4 + (col % 2), 3, 3]);
  }
  return rects;
}

export function paint(ctx, rects) {
  for (const [colour, x, y, w, h] of rects) {
    ctx.fillStyle = colour;
    ctx.fillRect(x, y, w, h);
  }
}
